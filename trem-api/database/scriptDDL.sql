-- CREATE TABLE
CREATE TABLE TIPO_MODAL (
    TPO_MODAL CHAR(1) NOT NULL,
    NME_TIPO_MODAL VARCHAR2(50),
    DSC_TIPO_MODAL VARCHAR2(200),

    CONSTRAINT TIPO_MODAL_PK
        PRIMARY KEY (TPO_MODAL)
);

CREATE TABLE SITUACAO_TREM (
    STA_TREM CHAR(1) NOT NULL,
    NME_SITUACAO_TREM VARCHAR2(50),
    DSC_SITUACAO_TREM VARCHAR2(200),

    CONSTRAINT SITUACAO_TREM_PK
        PRIMARY KEY (STA_TREM)
);

CREATE TABLE OPERADORA (
    CDG_OPERADORA INTEGER
        GENERATED BY DEFAULT AS IDENTITY,
    NME_OPERADORA VARCHAR2(100) NOT NULL,
    NMR_CNPJ VARCHAR2(14),

    CONSTRAINT OPERADORA_PK
        PRIMARY KEY (CDG_OPERADORA)
);

CREATE TABLE ESTACAO (
    CDG_ESTACAO INTEGER
        GENERATED BY DEFAULT AS IDENTITY,
    NME_ESTACAO VARCHAR2(100) NOT NULL,
    DSC_ENDERECO VARCHAR2(200),
    STA_ACESSIBILIDADE CHAR(1),
    STA_SITUACAO CHAR(1),

    CONSTRAINT ESTACAO_PK
        PRIMARY KEY (CDG_ESTACAO)
);

CREATE TABLE PASSAGEIRO (
    CDG_PASSAGEIRO INTEGER
        GENERATED BY DEFAULT AS IDENTITY,
    NME_PASSAGEIRO VARCHAR2(100) NOT NULL,
    NMR_CPF VARCHAR2(11) NOT NULL,
    DSC_EMAIL VARCHAR2(100),
    DTA_NASCIMENTO DATE,

    CONSTRAINT PASSAGEIRO_PK
        PRIMARY KEY (CDG_PASSAGEIRO)
);

CREATE TABLE LINHA (
    CDG_LINHA INTEGER
        GENERATED BY DEFAULT AS IDENTITY,
    NME_LINHA VARCHAR2(100) NOT NULL,
    COR_LINHA VARCHAR2(30),
    STA_SITUACAO CHAR(1),
    TIPO_MODAL_TPO_MODAL CHAR(1) NOT NULL,
    OPERADORA_CDG_OPERADORA INTEGER,

    CONSTRAINT LINHA_PK
        PRIMARY KEY (CDG_LINHA)
);

CREATE TABLE TREM (
    CDG_TREM INTEGER
        GENERATED BY DEFAULT AS IDENTITY,
    NME_MODELO VARCHAR2(50),
    QTD_CAPACIDADE INTEGER NOT NULL,
    SITUACAO_TREM_STA_TREM CHAR(1) NOT NULL,
    LINHA_CDG_LINHA INTEGER NOT NULL,

    CONSTRAINT TREM_PK
        PRIMARY KEY (CDG_TREM)
);

CREATE TABLE VIAGEM (
    CDG_VIAGEM INTEGER
        GENERATED BY DEFAULT AS IDENTITY,
    DTA_HORA_PARTIDA TIMESTAMP NOT NULL,
    DTA_HORA_CHEGADA TIMESTAMP,
    STA_SITUACAO CHAR(1),
    TREM_CDG_TREM INTEGER NOT NULL,

    CONSTRAINT VIAGEM_PK
        PRIMARY KEY (CDG_VIAGEM)
);

CREATE TABLE BILHETE (
    CDG_BILHETE INTEGER
        GENERATED BY DEFAULT AS IDENTITY,
    VLR_BILHETE NUMBER(10,2) NOT NULL,
    DTA_COMPRA TIMESTAMP NOT NULL,
    STA_SITUACAO CHAR(1),
    VIAGEM_CDG_VIAGEM INTEGER NOT NULL,
    PASSAGEIRO_CDG_PASSAGEIRO INTEGER NOT NULL,
    ESTACAO_CDG_ESTACAO_ORIGEM INTEGER NOT NULL,
    ESTACAO_CDG_ESTACAO_DESTINO INTEGER NOT NULL,

    CONSTRAINT BILHETE_PK
        PRIMARY KEY (CDG_BILHETE)
);

CREATE TABLE LINHA_ESTACAO (
    CDG_LINHA_ESTACAO INTEGER
        GENERATED BY DEFAULT AS IDENTITY,
    ORD_LINHA_ESTACAO INTEGER NOT NULL,
    LINHA_CDG_LINHA INTEGER NOT NULL,
    ESTACAO_CDG_ESTACAO INTEGER NOT NULL,

    CONSTRAINT LINHA_ESTACAO_PK
        PRIMARY KEY (CDG_LINHA_ESTACAO)
);


